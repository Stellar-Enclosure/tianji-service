CREATE TABLE tianji_agent.agent_process_dispatch (
    tenant_id bigint NOT NULL CHECK (tenant_id > 0),
    subject_issuer varchar(64) COLLATE "C" NOT NULL CHECK (subject_issuer ~ '^[0-9a-f]{64}$'),
    subject_id varchar(256) COLLATE "C" NOT NULL,
    idempotency_key varchar(128) COLLATE "C" NOT NULL,
    source_id varchar(128) COLLATE "C" NOT NULL,
    scope_type varchar(8) NOT NULL CHECK (scope_type IN ('BPMN', 'CMMN')),
    scope_id varchar(255) COLLATE "C" NOT NULL,
    occurrence_id varchar(255) COLLATE "C" NOT NULL,
    definition_sha256 char(64) COLLATE "C" NOT NULL CHECK (definition_sha256 ~ '^[0-9a-f]{64}$'),
    dispatch_not_after timestamptz NOT NULL,
    link_sha256 char(64) COLLATE "C" NOT NULL CHECK (link_sha256 ~ '^[0-9a-f]{64}$'),
    request_sha256 char(64) COLLATE "C" CHECK (request_sha256 ~ '^[0-9a-f]{64}$'),
    state varchar(8) NOT NULL CHECK (state IN ('OPEN', 'CLOSED')),
    run_id varchar(64),
    created_at timestamptz NOT NULL,
    closed_at timestamptz,
    PRIMARY KEY (tenant_id, subject_issuer, subject_id, idempotency_key),
    UNIQUE (tenant_id, source_id, scope_type, scope_id, occurrence_id),
    UNIQUE (tenant_id, run_id),
    FOREIGN KEY (tenant_id, run_id) REFERENCES tianji_agent.agent_run (tenant_id, run_id),
    CHECK ((state = 'OPEN' AND closed_at IS NULL) OR (state = 'CLOSED' AND closed_at IS NOT NULL)),
    CHECK ((run_id IS NULL AND request_sha256 IS NULL) OR (run_id IS NOT NULL AND request_sha256 IS NOT NULL))
);
